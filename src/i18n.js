export const LANGUAGE_KEY = 'spine-viewer:language:v1'

export const LANGUAGES = [
  // `short` is the compact form used in the drawer's narrow menu column; the
  // full `label` stays available for tooltips and other roomier placements.
  { id: 'zh', label: '简体中文', short: '中', htmlLang: 'zh-CN' },
  { id: 'en', label: 'English', short: 'EN', htmlLang: 'en' },
  { id: 'ja', label: '日本語', short: '日', htmlLang: 'ja' },
  { id: 'ko', label: '한국어', short: '한', htmlLang: 'ko' },
]

export function detectLanguage() {
  try {
    const saved = window.localStorage.getItem(LANGUAGE_KEY)
    if (LANGUAGES.some((language) => language.id === saved)) return saved
  } catch {
    // Ignore storage failures and fall back to the browser language.
  }

  const candidates = navigator.languages?.length
    ? navigator.languages
    : [navigator.language ?? 'en']

  for (const candidate of candidates) {
    const value = candidate.toLowerCase()
    if (value.startsWith('zh')) return 'zh'
    if (value.startsWith('ja')) return 'ja'
    if (value.startsWith('ko')) return 'ko'
    if (value.startsWith('en')) return 'en'
  }

  return 'en'
}

export function saveLanguage(language) {
  try {
    window.localStorage.setItem(LANGUAGE_KEY, language)
  } catch {
    // Language still works for the current session.
  }
}

